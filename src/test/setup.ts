import '@testing-library/jest-dom/vitest'

// jsdom no implementa matchMedia — necesario para useThemeStore (prefers-color-scheme)
if (!window.matchMedia) {
  window.matchMedia = (query: string): MediaQueryList => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })
}
